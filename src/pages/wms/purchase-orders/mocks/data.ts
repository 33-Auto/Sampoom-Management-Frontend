import type { Schemas } from "@/shared/model";export type POResDto = Schemas["POResDto"];

// 레거시 타입 (내부 사용)
export type PurchaseOrderListItem = {
  purchaseOrderId: number;
  orderNumber: string;
  vendorName: string;
  categoryName: string;
  groupName: string;
  categoryId?: number;
  groupId?: number;
  partCode: string;
  partName: string;
  unit: string;
  orderQuantity: number;
  inboundQuantity: number;
  restQuantity: number;
  price: number;
  status:
    | "REQUESTED"
    | "APPROVED"
    | "IN_PROGRESS"
    | "PARTIAL"
    | "COMPLETED"
    | "CANCELED";
  scheduledDate?: string;
  warehouseId: number;
};

// 상태 매핑: mock 데이터의 status를 API 스키마의 orderStatus로 변환
const mapStatusToOrderStatus = (
  status: PurchaseOrderListItem["status"],
): POResDto["orderStatus"] => {
  const statusMap: Record<
    PurchaseOrderListItem["status"],
    POResDto["orderStatus"]
  > = {
    REQUESTED: "UNDER_REVIEW",
    APPROVED: "PLAN_CONFIRMED",
    IN_PROGRESS: "IN_PROGRESS",
    PARTIAL: "IN_PROGRESS",
    COMPLETED: "COMPLETED",
    CANCELED: "DELAYED", // CANCELED는 스키마에 없으므로 DELAYED로 매핑
  };
  return statusMap[status] || "UNDER_REVIEW";
};

// PurchaseOrderListItem을 POResDto로 변환
export const transformToPOResDto = (item: PurchaseOrderListItem): POResDto => {
  return {
    purchaseOrderId: item.purchaseOrderId,
    orderNumber: item.orderNumber,
    categoryName: item.categoryName,
    groupName: item.groupName,
    partCode: item.partCode,
    partName: item.partName,
    unit: item.unit,
    orderQuantity: item.orderQuantity,
    inboundQuantity: item.inboundQuantity,
    restQuantity: item.restQuantity,
    price: item.price,
    scheduledDate: item.scheduledDate,
    createdAt: new Date().toISOString(), // 기본값
    orderStatus: mapStatusToOrderStatus(item.status),
  };
};

